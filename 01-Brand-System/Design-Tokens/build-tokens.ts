/** Generates tokens.css and tokens.ts from tokens.json. Run: npm run tokens */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveColors, tokens } from './resolve.ts';

const here = dirname(fileURLToPath(import.meta.url));
const colors = resolveColors();

const groups: Array<[string, Record<string, string>]> = [
  ['size', tokens.size],
  ['leading', tokens.leading],
  ['tracking', tokens.tracking],
  ['space', tokens.space],
  ['radius', tokens.radius],
  ['shadow', tokens.shadow],
  ['motion', tokens.motion as Record<string, string>],
  ['layout', tokens.layout],
];

const css = [
  '/* GENERATED by build-tokens.ts from tokens.json — do not edit by hand. */',
  ':root {',
  ...Object.entries(colors).map(([k, v]) => `  --c-${k}: ${v};`),
  `  --font-display: ${tokens.font.display};`,
  `  --font-body: ${tokens.font.body};`,
  `  --font-mono: ${tokens.font.mono};`,
  ...groups.flatMap(([g, obj]) => Object.entries(obj).map(([k, v]) => `  --${g}-${k}: ${v};`)),
  '}',
  '',
].join('\n');

const ts = [
  '/* GENERATED by build-tokens.ts from tokens.json — do not edit by hand. */',
  `export const colors = ${JSON.stringify(colors, null, 2)} as const;`,
  `export const fonts = ${JSON.stringify({ display: tokens.font.display, body: tokens.font.body, mono: tokens.font.mono }, null, 2)} as const;`,
  `export const breakpoints = ${JSON.stringify(tokens.breakpoint, null, 2)} as const;`,
  'export type ColorToken = keyof typeof colors;',
  '',
].join('\n');

writeFileSync(join(here, 'tokens.css'), css);
writeFileSync(join(here, 'tokens.ts'), ts);
console.log(`tokens: ${Object.keys(colors).length} colours → tokens.css, tokens.ts`);
